"""One immutable diagnosis/helper/synthetic capture; excludes future replay."""
import hashlib
import json
from pathlib import Path
import shutil
import subprocess


HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
OUT = HERE.parent / "immutable-expm-diagnosis-pade13-synthetic-20261009"
assert not OUT.exists()
OUT.mkdir()


def sha(p):
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()


files, large = [], []
sources = [(str(p.relative_to(HERE)), p) for p in sorted(HERE.rglob("*"))
           if p.is_file() and "__pycache__" not in p.parts and p.suffix != ".pyc"]
root_review = HERE.parent / "finite-rb-limited-matrix-growth-pade13-20261009/root-source-review.json"
sources += [("pade13-candidate/root-source-review.json", root_review)]
original_receipt = HERE.parent / "finite-rb-limited-matrix-growth-20261009/J0-N8-rb98-growth001/receipt.json"
sources += [("original-failed-growth-receipt.json", original_receipt)]
for rel, p in sources:
    entry = {"path": rel, "origin": str(p), "bytes": p.stat().st_size, "sha256": sha(p)}
    if entry["bytes"] > 1048576:
        large.append(entry)
        continue
    target = OUT / rel
    target.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(p, target)
    assert sha(target) == entry["sha256"] == sha(p)
    files.append(entry)
readme = (
    "Immutable original SciPy failure diagnosis and fresh fixed-Pade13 synthetic gate.\n"
    "The actual isolated SciPy call/power probes are diagnosis only and remain failed.\n"
    "The new helper gates evaluate constructed synthetic inputs only; no actual\n"
    "scientific operator was evaluated with that helper in this capsule.\n"
    "Parent/source reviews support separately admitted finite-matrix replay only.\n"
    "Original failed attempts and all limitations remain. Large files are metadata\n"
    "only if larger than1MiB. No PDE/native/nonlinear/scri/BH acceptance.\n"
)
(OUT / "README.md").write_text(readme)
files.append({"path": "README.md", "origin": "generated by freeze_synthetic.py",
              "bytes": (OUT / "README.md").stat().st_size, "sha256": sha(OUT / "README.md")})
index = {"kind": "Immutable expm diagnosis and fixed-Pade13 synthetic gate",
         "git_head": subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=ROOT, text=True).strip(),
         "production_source_commit": "27c19d20696ea6dd4704032c51dfd026218f64f2",
         "source_directory": str(HERE), "helper_sha256": "0654c3ba8884dc467aa1c4665fc4758a3abddf58189e2702f7e8cfc90d2e79b7",
         "files": files, "large_external_records": large,
         "small_file_count": len(files), "small_bytes": sum(x["bytes"] for x in files),
         "scientific_helper_replay_in_this_capsule": False}
(OUT / "index.json").write_text(json.dumps(index, indent=2, allow_nan=False) + "\n")
for entry in files:
    assert sha(OUT / entry["path"]) == entry["sha256"]
    if Path(entry["origin"]).is_file():
        assert sha(entry["origin"]) == entry["sha256"]
print(json.dumps({"path": str(OUT / "index.json"), "sha256": sha(OUT / "index.json"),
                  "files": len(files), "bytes": index["small_bytes"], "large": len(large)}))
