class SBPOperators(RadialOperators):
    def __init__(self,r,width=7,quadrature_width=7):
        if len(r)<19 or r[0]<0 or r[-1]!=1 or max(abs(np.diff(r)-np.diff(r)[0]))>1e-14:
            raise ValueError('SBP6/3 requires a uniform nonnegative grid ending at1 with >=19 points')
        super().__init__(r,width,quadrature_width,puncture=True,allow_puncture_node=True)
        self.spacing=r[1]-r[0];n=len(r);self.norm=np.ones(n)
        self.norm[:6]=H;self.norm[-6:]=H[::-1]
        self.sindex=np.zeros((n,9),dtype=int);self.sweights=np.zeros((n,9))
        for i in range(n):
            if i<6:self.sindex[i]=np.arange(9);self.sweights[i]=LEFT[i]
            elif i>=n-6:self.sindex[i]=np.arange(n-1,n-10,-1);self.sweights[i]=-LEFT[n-1-i]
            else:
                self.sindex[i,:6]=i+np.array([-3,-2,-1,1,2,3])
                self.sweights[i,:6]=[-1/60,3/20,-3/4,3/4,-3/20,1/60]
        self.sweights/=self.spacing

    def first(self,values):
        # Difference form preserves constants without changing physical values.
        if values.ndim==1:return np.sum(self.sweights*(values[self.sindex]-values[:,None]),axis=1)
        return np.einsum('ij,ijf->if',self.sweights,values[self.sindex]-values[:,None,:])

    def derivatives(self,values,parity):
        first=self.first(np.asarray(values));return first,self.first(first)

    def endpoint_first(self,values):return self.first(np.asarray(values))[-1]
