#!/usr/bin/env python3
"""Regenerate small native-test references from the retained NumPy SVD plan."""
from pathlib import Path
import hashlib
import importlib.util
import sys
import numpy as np
ROOT=Path(__file__).resolve().parents[2]
STUDY=ROOT/'docs/hyperbolic-shift-3d/reproduction/scri-dissipation-prototype-v1'
spec=importlib.util.spec_from_file_location('angular_prototype',STUDY/'prototype.py')
module=importlib.util.module_from_spec(spec);sys.modules[spec.name]=module;spec.loader.exec_module(module)
source=STUDY/'cases/n6-p7/plan.npz';saved=np.load(source)
plan=module.Plan(6,7,*[saved[k] for k in ('points','labels','mass','starts','rows','indices','coefficients')],{})
rows=[0,53,107,215]
terms=[]
for row in rows:
    for index in range(plan.starts[row],plan.starts[row+1]):
        donor=int(plan.indices[index])
        if donor!=row:terms.append((row,donor,plan.coefficients[index]))
u=np.array([np.sin(.37*i)+np.cos(.013*i*i) for i in range(len(plan.mass))])
q=plan.apply_q(u)
lines=['// Generated by generate_angular_dissipation_reference.py; do not hand edit.',
       '// Retained NumPy SVD plan SHA256: '+hashlib.sha256(source.read_bytes()).hexdigest(),
       '#ifndef TEST_ANGULAR_DISSIPATION_REFERENCE_HPP_',
       '#define TEST_ANGULAR_DISSIPATION_REFERENCE_HPP_',
       'namespace angular_reference {',
       'struct Term {int row,donor;double coefficient;};',
       'inline constexpr Term terms[] = {']
lines += ['  {%d,%d,%.17g},'%t for t in terms]
lines += ['};','inline constexpr double source[] = {']
lines += ['  %.17g,'%value for value in q]
lines += ['};','}  // namespace angular_reference','#endif','']
Path(__file__).with_name('angular_dissipation_reference.hpp').write_text('\n'.join(lines))
