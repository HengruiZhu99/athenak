#!/usr/bin/env python3
"""Generate exact six-active-node radial derivative coefficients."""
from fractions import Fraction as F
from pathlib import Path
import math

def solve(a,b):
 a=[list(row)+[value] for row,value in zip(a,b)]
 for k in range(len(b)):
  pivot=next(i for i in range(k,len(b)) if a[i][k]);a[k],a[pivot]=a[pivot],a[k]
  scale=a[k][k];a[k]=[x/scale for x in a[k]]
  for i in range(len(b)):
   if i!=k:
    scale=a[i][k];a[i]=[x-scale*y for x,y in zip(a[i],a[k])]
 return [row[-1] for row in a]

def weights(depth,d):
 x=[F(j-5+depth) for j in range(6)]
 w=solve([[v**k for v in x] for k in range(6)],[F(math.factorial(d) if k==d else 0) for k in range(6)])
 for k in range(6):assert sum(c*v**k for c,v in zip(w,x))==(math.factorial(d) if k==d else 0)
 return '{'+','.join('Real(%d)/Real(%d)'%(c.numerator,c.denominator) for c in w)+'}'
text='''// Generated by tst/cubed_sphere/generate_interior_radial.py; exact moments.
// Research candidate, NOT an SBP operator or a complete boundary condition.
// Nodes are last_active-5,...,last_active; depth=last_active-current in [0,2].
// Differentiate deviations; analytic background derivatives are added separately.
#ifndef MESH_CUBED_SPHERE_INTERIOR_RADIAL_HPP_
#define MESH_CUBED_SPHERE_INTERIOR_RADIAL_HPP_
namespace cubed_sphere {
template<class Sample>
KOKKOS_INLINE_FUNCTION Real InteriorRadialFirst(const Sample &sample,int depth,Real h) {
 const Real w[3][6]={FIRST};
 Real out=0,anchor=sample(5);
 for(int j=0;j<6;++j)out+=w[depth][j]*(sample(j)-anchor);
 return out/h;
}
template<class Sample>
KOKKOS_INLINE_FUNCTION Real InteriorRadialSecond(const Sample &sample,int depth,Real h) {
 const Real w[3][6]={SECOND};
 Real out=0,anchor=sample(5);
 for(int j=0;j<6;++j)out+=w[depth][j]*(sample(j)-anchor);
 return out/(h*h);
}
} // namespace cubed_sphere
#endif
'''.replace('FIRST',','.join(weights(depth,1) for depth in range(3))).replace('SECOND',','.join(weights(depth,2) for depth in range(3)))
Path('src/mesh/cubed_sphere/interior_radial.hpp').write_text(text)
