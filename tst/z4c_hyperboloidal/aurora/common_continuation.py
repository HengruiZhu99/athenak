def require(value, message):
    if not value:
        raise ValueError(message)


def sha(path):
    h=hashlib.sha256()
    with Path(path).open('rb') as stream:
        for chunk in iter(lambda:stream.read(8*1024*1024),b''):
            h.update(chunk)
    return h.hexdigest()


def job_number(value):
    require(isinstance(value,str) and re.fullmatch(r'\d+(?:\.[A-Za-z0-9.-]+)?',value),
            'invalid recorded PBS job identifier')
    return value.split('.')[0]


def check_science(science, review, science_sha, checkpoint_sha, previous_segment):
    end=CYCLES[previous_segment]
    require(science['schema']=='native-n12-common-science-admission-v1' and
            science['passed'] is True and science['segment']==previous_segment and
            science['end_cycle']==end and science['through_5m_complete'] is False and
            science['checkpoint_sha256']==checkpoint_sha,
            'missing or mismatched completed predecessor scientific admission')
    expected={'0',str(end)} if previous_segment==1 else {str(end)}
    require(set(science['comparisons'])==expected and
            all(x['passed'] is True and x['writer_mpi_ranks']==24
                for x in science['comparisons'].values()) and
            science['history_completed_prefix_passed'] is True and
            science['structural']['structural_cadence_passed'] is True and
            science['structural']['segment']==previous_segment and
            science['structural']['end_cycle']==end and
            science['missing_future_common_steps']==CYCLES[previous_segment+1:],
            'incomplete predecessor fields/history/structural coverage')
    metric=science['stage_metrics']
    require(metric['schema']=='native-step-metrics-v1' and metric['passed'] is True and
            metric['through_step']==end and metric['stage_rows']==4*end and
            metric['ranks']==24 and metric['gate']=='long' and metric['failed_values']==0 and
            metric['completed_steps']==list(range(1,end+1)),
            'missing complete cumulative predecessor stage metrics')
    require(review['schema']=='native-n12-common-independent-review-v1' and
            review['passed'] is True and review['end_cycle']==end and
            review['science_admission_sha256']==science_sha and
            review['checkpoint_sha256']==checkpoint_sha,
            'independent review is bound to another science report/checkpoint')


def check_submission(record, previous_segment):
    require(record['schema']=='native-n12-common-segment-submission-v1' and
            record['segment']==previous_segment and record['nodes']==2 and record['ranks']==24 and
            (record['start_cycle'],record['end_cycle'])==tuple(CYCLES[previous_segment-1:previous_segment+1]),
            'previous job submission does not match the accepted segment')
    return job_number(record['job_id'])


def check_execution_record(science, case_name, name, actual_sha):
    """Bind one portable execution path, never any matching digest in the report."""
    matches=[digest for path,digest in science['input_sha256'].items()
             if Path(path).parts[-3:]==('runs',case_name,name)]
    require(len(matches)==1 and matches[0]==actual_sha,
            'actual predecessor execution record differs or has ambiguous provenance: '+name)


def pbs_text(segment, root):
    require(3<=segment<=10, 'supported prepared continuations are3..10')
    directory=root/f'validation/common-next-{segment:02d}'
    return f'''#!/bin/bash -l
# Generated by common_continuation.py; no automatic submission or chaining.
#PBS -A CompactBinaryMerger
#PBS -N native-n12-common{segment}
#PBS -q debug
#PBS -l select=2
#PBS -l walltime=01:00:00
#PBS -l filesystems=home:flare
#PBS -j oe
set -euo pipefail
cd {shlex.quote(str(directory))}
sha256sum -c launchers.sha256
/usr/bin/python3.11 common_continuation.py preflight --root {shlex.quote(str(root))} \\
 --acceptance acceptance.json --output preflight-in-job.json
cd {shlex.quote(str(root/'validation/full-n12'))}
sha256sum -c launchers.sha256
exec bash run-common-segment.sh {segment}
'''


def prepare(args):
    previous=args.segment-1
    science=json.loads(args.science.read_text());review=json.loads(args.review.read_text())
    submission=json.loads(args.previous_submission.read_text())
    previous_job=check_submission(submission,previous)
    check_science(science,review,sha(args.science),science['checkpoint_sha256'],previous)
    output=args.output.resolve();output.mkdir(parents=True,exist_ok=False)
    remote=args.root/f'validation/common-next-{args.segment:02d}'
    acceptance=dict(schema='native-n12-continuation-input-v2',segment=args.segment,
        start_cycle=CYCLES[previous],end_cycle=CYCLES[args.segment],
        previous_job=previous_job,science_admission_sha256=sha(args.science),
        checkpoint_sha256=science['checkpoint_sha256'],
        independent_review=dict(path=str(remote/'previous-review.json'),sha256=sha(args.review)),
        previous_submission=dict(path=str(remote/'previous-submission.json'),
                                 sha256=sha(args.previous_submission)),
        scope='Only this segment; no automatic submission or later continuation')
    (output/'acceptance.json').write_text(json.dumps(acceptance,indent=2)+'\n')
    sources=[(args.science,'previous-science.json'),(args.review,'previous-review.json'),
             (args.previous_submission,'previous-submission.json'),
             (Path(__file__).resolve(),'common_continuation.py')]
    origins={}
    for source,name in sources:
        shutil.copyfile(source,output/name)
        origins[name]=dict(source=str(source.resolve()),sha256=sha(source))
    (output/'run.pbs').write_text(pbs_text(args.segment,args.root))
    (output/'staging-origin.json').write_text(json.dumps(dict(
        schema='native-n12-reusable-continuation-staging-v1',segment=args.segment,
        files=origins,submitted=False,runtime_changes=False),indent=2)+'\n')
    files=sorted(p for p in output.iterdir() if p.is_file())
    (output/'launchers.sha256').write_text(''.join(sha(p)+'  '+p.name+'\n' for p in files))
    print(json.dumps(dict(prepared=True,submitted=False,segment=args.segment,
        output=str(output),remote_directory=str(remote),previous_job=previous_job,
        install_predecessor_science=str(args.root/f'runs/native-n12-common-{previous:02d}'/
                                       'continuation-admission.json')),indent=2))


def preflight(args):
    root=args.root.resolve();scripts=root/'validation/full-n12'
    require(not args.output.exists(), 'refuse to overwrite preflight evidence')
    acceptance=json.loads(args.acceptance.read_text());segment=acceptance['segment']
    require(acceptance['schema']=='native-n12-continuation-input-v2' and 3<=segment<=10 and
            (acceptance['start_cycle'],acceptance['end_cycle'])==tuple(CYCLES[segment-1:segment+1]),
            'wrong continuation interval')
    previous=segment-1;case=root/f'runs/native-n12-common-{previous:02d}'
    science_path=case/'continuation-admission.json'
    review_path=Path(acceptance['independent_review']['path'])
    submission_path=Path(acceptance['previous_submission']['path'])
    require(sha(science_path)==acceptance['science_admission_sha256'] and
            sha(review_path)==acceptance['independent_review']['sha256'] and
            sha(submission_path)==acceptance['previous_submission']['sha256'],
            'accepted science/review/job proof changed')
    science=json.loads(science_path.read_text());review=json.loads(review_path.read_text())
    previous_job=check_submission(json.loads(submission_path.read_text()),previous)
    require(previous_job==job_number(acceptance['previous_job']), 'previous job binding changed')
    checkpoint=case/'rst'/f'native_n12_5M.{previous:05d}.rst';checkpoint_sha=sha(checkpoint)
    require(checkpoint_sha==acceptance['checkpoint_sha256'], 'accepted checkpoint changed')
    check_science(science,review,sha(science_path),checkpoint_sha,previous)
    for name in ['command.txt','exit-code.txt']:
        check_execution_record(science,case.name,name,sha(case/name))
    require((case/'exit-code.txt').read_text().strip()=='0', 'predecessor executable failed')
    status=subprocess.run(['qstat','-xf',previous_job],capture_output=True,text=True,check=True).stdout
    require('job_state = F' in status and 'Exit_status = 0' in status and
            re.search(r'^\s*Job_Name = native-n12-common'+str(previous)+r'\s*$',status,re.M),
            'previous PBS job did not complete the expected common interval')
    require(sha(scripts/'admission.json')==SHORT_ADMISSION, 'initial short admission changed')
    for name,digest in FROZEN_HELPERS.items():
        require(sha(scripts/name)==digest, 'frozen shared launcher/helper changed: '+name)
    spec=importlib.util.spec_from_file_location('frozen_common_audit',scripts/'common_segment_audit.py')
    audit=importlib.util.module_from_spec(spec);spec.loader.exec_module(audit)
    reference=root/'runs/n12-native-gpu-eight-two/rst/native_n12_5M.00000.rst'
    require(sha(reference)==audit.INITIAL_SHA, 'admitted initial reference changed')
    header=audit.validate(audit.checkpoint(checkpoint),audit.checkpoint(reference),previous,CYCLES[previous])
    audit.verify_runtime(root)
    observer=root/'validation/step-observer'
    require(sha(observer/'build/athena-step-observer')==OBSERVED, 'observed executable changed')
    verify=subprocess.run(['/usr/bin/python3.11',str(observer/'native_step_observer.py'),
        'verify','--output',str(observer/'build')],capture_output=True,text=True,check=True)
    report=dict(schema='native-n12-continuation-preflight-v2',passed=True,segment=segment,
        start_cycle=CYCLES[previous],end_cycle=CYCLES[segment],predecessor_job=previous_job,
        execution_job_id=os.environ.get('PBS_JOBID'),checkpoint=header,
        checked_utc=datetime.datetime.now(datetime.timezone.utc).isoformat(),
        science_admission_sha256=sha(science_path),independent_review_sha256=sha(review_path),
        previous_submission_sha256=sha(submission_path),acceptance_sha256=sha(args.acceptance),
        short_admission_sha256=SHORT_ADMISSION,frozen_helpers=FROZEN_HELPERS,
        observer_verify_stdout=verify.stdout,observer_verify_stderr=verify.stderr,
        restart_entry='unchanged shared runner; ordinary -r, no -i, no -t',
        scope='Only this interval; no automatic submission or later continuation')
    args.output.write_text(json.dumps(report,indent=2)+'\n');print(json.dumps(report,indent=2))


def main():
    parser=argparse.ArgumentParser(description=__doc__);sub=parser.add_subparsers(dest='mode',required=True)
    p=sub.add_parser('prepare');p.add_argument('--segment',type=int,choices=range(3,11),required=True)
    for name in ['science','review','previous-submission','output']:
        p.add_argument('--'+name,type=Path,required=True)
    p.add_argument('--root',type=Path,default=ROOT)
    p=sub.add_parser('preflight');p.add_argument('--root',type=Path,default=ROOT)
    p.add_argument('--acceptance',type=Path,required=True);p.add_argument('--output',type=Path,required=True)
    args=parser.parse_args();prepare(args) if args.mode=='prepare' else preflight(args)


if __name__=='__main__':
    main()
